const PROFILE_MARKER = `# Generated by \`${NAME} install\``;

function profileToml(config) {
  return `${PROFILE_MARKER}. Use with: codex -p ${PROFILE}
model_provider = "${PROFILE}"
# The configured id, so the proxy routes the effort of every generation.
model = "${config.model}"
# Where a turn starts; the proxy moves it between ${config.ladder.join(' and ')}.
model_reasoning_effort = "${config.defaultEffort}"

[model_providers.${PROFILE}]
name = "Laya GPT"
base_url = "http://${config.host}:${config.port}/v1"
wire_api = "responses"
requires_openai_auth = true
`;
}

function codexHomeDir() {
  return process.env.CODEX_HOME || path.join(os.homedir(), '.codex');
}

function install(config, force, global) {
  const codexHome = codexHomeDir();
  const file = path.join(codexHome, `${PROFILE}.config.toml`);
  if (fs.existsSync(file) && !force && !fs.readFileSync(file, 'utf8').startsWith(PROFILE_MARKER)) {
    throw new Error(`${file} exists and was not written by ${NAME}; rerun with --force to overwrite`);
  }
  fs.mkdirSync(codexHome, { recursive: true });
  fs.writeFileSync(file, profileToml(config));
  console.log(`wrote ${file}\nrun: ${NAME} codex   (or start "${NAME} serve" and use: codex -p ${PROFILE})`);
  if (global) installGlobal(config, codexHome);
}

function readIfExists(file) {
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
}

function installGlobal(config, codexHome) {
  const file = path.join(codexHome, 'config.toml');
  const before = readIfExists(file);
  const after = addGlobal(before ?? '', config);
  // The first install keeps a copy of the untouched file; later installs leave it alone.
  const backup = `${file}.${NAME}.bak`;
  if (before != null && !hasGlobal(before) && !fs.existsSync(backup)) fs.writeFileSync(backup, before);
  fs.writeFileSync(file, after);
  console.log(`made ${NAME} the default provider in ${file}${before != null ? ` (backup: ${backup})` : ''}\n`
    + `every Codex client (desktop app, IDE, plain "codex") now needs "${NAME} serve" running; undo with: ${NAME} uninstall`);
}

function claudeSkillsDir() {
  return path.join(os.homedir(), '.claude', 'skills');
}

/** Installs the laya-gpt and laya-deploy skills into Codex, and into Claude Code when asked. */
function installAgentSkills(deploy, { claude = false, force = false } = {}) {
  const sources = skillSources(REPO_DIR, deploy);
  if (!sources.some((s) => s.dir.startsWith(path.join(deploy, 'skills') + path.sep))) {
    console.log(`no laya-deploy skills in ${deploy}; run "${NAME} setup" first (the ${NAME} skill is still installed)`);
  }
  const targets = [path.join(codexHomeDir(), 'skills'), ...(claude ? [claudeSkillsDir()] : [])];
  for (const dir of targets) {
    const { installed, skipped } = installSkills(sources, dir, { force });
    if (installed.length > 0) console.log(`installed ${installed.join(', ')} into ${dir}`);
    for (const name of skipped) {
      console.log(`skipped ${name}: ${path.join(dir, name)} exists and was not written by ${NAME}; rerun with --force`);
    }
  }
}

function uninstall() {
  const codexHome = codexHomeDir();
  const main = path.join(codexHome, 'config.toml');
  const text = readIfExists(main);
  if (text != null && hasGlobal(text)) {
    fs.writeFileSync(main, removeGlobal(text));
    console.log(`restored ${main}`);
  }
  const profile = path.join(codexHome, `${PROFILE}.config.toml`);
  if (readIfExists(profile)?.startsWith(PROFILE_MARKER)) {
    fs.rmSync(profile);
    console.log(`removed ${profile}`);
  }
  for (const dir of [path.join(codexHome, 'skills'), claudeSkillsDir()]) {
    for (const name of removeSkills(dir)) console.log(`removed skill ${name} from ${dir}`);
  }
}

/** @returns {Promise<object|null>} the /laya/health payload of whatever answers the port, or null */
async function probe(config) {
  try {
    const res = await fetch(`http://${config.host}:${config.port}/laya/health`, { signal: AbortSignal.timeout(500) });
    return res.ok ? await res.json() : null;
  } catch {
    return null;
  }
}

function foreignDescription(health) {
  return health.app ? `app "${String(health.app).slice(0, 40)}"` : 'no app id';
}

// Another server holds the port: it is reported, never signalled or reused.
function foreignPortMessage(config, health) {
  return `port ${config.port} is answered by ${foreignDescription(health)}, not a ${NAME} proxy; set LAYA_PORT to another port`;
}

async function ensureProxy(config) {
  const running = await probe(config);
  if (running) {
    if (!isOurProxy(running)) throw new Error(foreignPortMessage(config, running));
    const check = compareBuild(running);
    if (check.status === 'stale') console.error(`${NAME}: warning: ${check.message}`);
    return;
  }
  fs.mkdirSync(config.home, { recursive: true });
  const out = fs.openSync(path.join(config.home, 'proxy.log'), 'a');
  const self = fileURLToPath(import.meta.url);
  spawn(process.execPath, [self, 'serve'], { detached: true, stdio: ['ignore', out, out], windowsHide: true }).unref();
  for (let i = 0; i < 30; i++) {
    await new Promise((r) => setTimeout(r, 100));
    if (isOurProxy(await probe(config))) return;
  }
  throw new Error(`proxy did not start; see ${path.join(config.home, 'proxy.log')}`);
}

// On Windows `codex` is a .cmd shim; running it through cmd.exe would re-parse the
// user's arguments (`&`, `%VAR%`). Launch the npm package's JS entry with node instead.
function codexCommand() {
  if (process.platform !== 'win32') return { file: 'codex', prefix: [] };
  const dirs = (process.env.PATH ?? '').split(path.delimiter).filter(Boolean);
  if (process.env.APPDATA) dirs.push(path.join(process.env.APPDATA, 'npm'));
  for (const dir of dirs) {
    const entry = path.join(dir, 'node_modules', '@openai', 'codex', 'bin', 'codex.js');
    if (fs.existsSync(path.join(dir, 'codex.cmd')) && fs.existsSync(entry)) {
      return { file: process.execPath, prefix: [entry] };
    }
  }
  throw new Error(`cannot find the npm-installed Codex (codex.cmd + @openai/codex); start "${NAME} serve" and run: codex -p ${PROFILE}`);
}

async function runCodex(config, args) {
  await ensureProxy(config);
  const { file, prefix } = codexCommand();
  const child = spawn(file, [...prefix, '-p', PROFILE, ...args], { stdio: 'inherit' });
  child.on('error', (err) => {
    console.error(`${NAME}: cannot start codex: ${err.message}`);
    process.exit(1);
  });
  child.on('exit', (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
}

async function portOwnerHint(config) {
  const running = await probe(config);
  if (!running) return ` (port ${config.port} in use by something else; set LAYA_PORT)`;
  if (isOurProxy(running)) return `; a ${NAME} proxy is already there: ${compareBuild(running).message}`;
  return `; ${foreignPortMessage(config, running)}`;
}

function serve(config) {
  const { server } = createProxy(config);
  server.on('error', async (err) => {
    if (err.code === 'EADDRINUSE') {
      const running = await probe(config);
      if (isOurProxy(running)) {
        console.log(`${NAME}: ${compareBuild(running).message}`);
        console.log('Following decisions from the configured LAYA_HOME. Older proxies record decisions after responses complete.');
        console.log('Send requests through laya-gpt codex or codex -p layagpt; Ctrl+C stops viewing only.');
        return tail(config, running.eventStream === true);
      }
    }
    const hint = err.code === 'EADDRINUSE' ? await portOwnerHint(config) : '';
    console.error(`${NAME}: ${err.message}${hint}`);
    process.exit(1);
  });
  server.listen(config.port, config.host, async () => {
    console.log(`${NAME} v${VERSION} (build ${BUILD}) listening on http://${config.host}:${config.port}/v1  `
      + `mode=${config.mode} model=${config.model} default=${config.defaultEffort} ladder=${config.ladder.join('→')} `
      + `continue=${config.continueTurns ? `on (max ${config.maxContinues})` : 'off'} nudge=${config.nudge ? 'on' : 'off'}`);
    if (config.mode !== 'laya') return;
    // The proxy serves at once; until laya answers, decisions fall back to the rules.
    try {
      const laya = await ensureLaya(config);
      console.log(`laya (${config.decisionModel}): ${laya.state}, ${laya.detail}`);
    } catch (err) {
      console.error(`${NAME}: cannot start laya: ${err.message}; decisions use the rules`);
    }
  });
}

function runStep(file, args, cwd) {
  console.log(`> ${[path.basename(file), ...args].join(' ')}`);
  const r = spawnSync(file, args, { cwd, stdio: 'inherit' });
  if (r.error) throw new Error(`cannot run ${file}: ${r.error.message}`);
  if (r.status !== 0) throw new Error(`${path.basename(file)} ${args[0]} failed (exit ${r.status})`);
}

// Installs laya-deploy beside laya-gpt: about 3 GB for torch and laya, plus the checkpoint.
function setup(config, rest) {
  const i = rest.indexOf('--dir');
  const dir = i >= 0 && rest[i + 1] ? path.resolve(rest[i + 1]) : deployDir(process.env, config.home);
  if (fs.existsSync(path.join(dir, 'pyproject.toml'))) {
    console.log(`using the laya-deploy checkout at ${dir}`);
  } else {
    if (fs.existsSync(dir) && fs.readdirSync(dir).length > 0) throw new Error(`${dir} exists and is not a laya-deploy checkout`);
    runStep('git', ['clone', DEPLOY_REPO, dir]);
  }
  runStep('uv', ['sync', '--extra', 'model'], dir);
  const models = config.decisionModel === 'auto' ? ['english', 'multilingual'] : [config.decisionModel];
  runStep(venvPython(dir), ['-m', 'laya_deploy.cli', 'pull', '--models', ...models], dir);
  rememberDeployDir(config.home, dir);
  console.log(`laya-deploy is ready at ${dir}; "${NAME} serve" or "${NAME} codex" starts it when needed`);
  try {
    installAgentSkills(dir);
  } catch (err) {
    console.warn(`${NAME}: warning: cannot install skills: ${err.message}`);
  }
}

async function status(config) {
  const running = await probe(config);
  if (!running) {
    console.log(`no ${NAME} proxy on http://${config.host}:${config.port} (code on disk: v${VERSION} build ${BUILD})`);
    process.exitCode = 1;
    return;
  }
  if (!isOurProxy(running)) {
    console.log(foreignPortMessage(config, running));
    process.exitCode = 1;
    return;
  }
  const check = compareBuild(running);
  console.log(`${check.message}  mode=${running.mode}`);
  if (check.status === 'stale') process.exitCode = 1;
  if (running.mode === 'laya') await layaStatus(config);
}

async function layaStatus(config) {
  const health = await layaHealth(config);
  const pid = startedPid(config);
  const owner = pid ? `started by ${NAME}, pid ${pid}` : 'started by hand';
  if (health) console.log(`laya: up (${owner}), loaded ${(health.loaded ?? []).join(', ') || 'nothing yet'}`);
  else console.log(pid ? `laya: loading (pid ${pid})` : 'laya: not running; decisions use the rules');
}

const STOP_WAIT_MS = 3000;
const STOP_POLL_MS = 100;

// Stops the laya-gpt proxy that holds the port, including one started in the
// background by `laya-gpt codex`. The PID comes from /laya/health, and only a
// payload that names this app is ever signalled.
async function stop(config) {
  const layaPid = stopLaya(config);
  if (layaPid) console.log(`stopped laya (pid ${layaPid})`);
  const running = await probe(config);
  if (!running) {
    console.log(`no ${NAME} proxy on http://${config.host}:${config.port}`);
    return;
  }
  if (!isOurProxy(running)) {
    console.error(`${NAME}: ${foreignPortMessage(config, running)}; not stopping it`);
    process.exitCode = 1;
    return;
  }
  if (!Number.isInteger(running.pid)) {
    console.error(`${NAME}: the proxy on port ${config.port} predates "${NAME} stop" and does not report its PID; stop it with:\n`
      + `  PowerShell: Stop-Process -Id (Get-NetTCPConnection -LocalPort ${config.port} -State Listen).OwningProcess\n`
      + `  macOS/Linux: kill $(lsof -t -iTCP:${config.port} -sTCP:LISTEN)`);
    process.exitCode = 1;
    return;
  }
  try {
    process.kill(running.pid);
  } catch (err) {
    if (err.code !== 'ESRCH') throw new Error(`cannot stop pid ${running.pid}: ${err.message}`);
  }
  for (let waited = 0; waited < STOP_WAIT_MS; waited += STOP_POLL_MS) {
    // Gone, or the port now belongs to another process: our proxy has stopped.
    const now = await probe(config);
    if (!isOurProxy(now) || now.pid !== running.pid) {
      console.log(`stopped ${NAME} proxy (pid ${running.pid}, v${running.version} build ${running.build})`);
      return;
    }
    await new Promise((r) => setTimeout(r, STOP_POLL_MS));
  }
  console.error(`${NAME}: pid ${running.pid} is still answering on port ${config.port} after ${STOP_WAIT_MS} ms`);
  process.exitCode = 1;
}

function tail(config, live = fs.existsSync(config.eventFile)) {
  const file = live ? config.eventFile : config.logFile;
  let size = fs.existsSync(file) ? fs.statSync(file).size : 0;
  let pending = '';
  let decoder = new StringDecoder('utf8');
  console.log(`following ${file} (Ctrl+C to stop)`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.watchFile(file, { interval: 300 }, (cur) => {
    if (cur.size <= size) {
      if (cur.size < size) { pending = ''; decoder = new StringDecoder('utf8'); }
      size = cur.size;
      return;
    }
    const fd = fs.openSync(file, 'r');
    const buf = Buffer.alloc(cur.size - size);
    fs.readSync(fd, buf, 0, buf.length, size);
    fs.closeSync(fd);
    size = cur.size;
    const lines = (pending + decoder.write(buf)).split('\n');
    pending = lines.pop();
    for (const line of lines.filter(Boolean)) {
      try {
        const record = JSON.parse(line);
        if (record.type === 'completed') console.log(`Laya  completed ${record.id}  HTTP ${record.status}`);
        else if (record.type === 'failed') console.log(`Laya  failed ${record.id}  ${record.error}`);
        else console.log(formatDecision(record));
      } catch {
        // Skip malformed complete records.
      }
    }
  });
}

function rankEffort(effort) {
  const i = EFFORTS.indexOf(effort);
  return i >= 0 ? i : EFFORTS.length;
}

// New records contain each upstream generation; old logs only have one usage snapshot.
function generationsOf(row) {
  return row.generations?.length ? row.generations : [{ effort: row.effort, usage: row.usage }];
}

/** Groups generations by effort in ladder order; rows that set only the model go under "-". */
function groupByEffort(rows) {
  const groups = new Map();
  for (const r of rows.flatMap(generationsOf)) {
    const effort = r.effort ?? '-';
    const g = groups.get(effort) ?? { effort, gens: 0, reasoning: 0, output: 0 };
    const t = usageTokens(r.usage);
    g.gens++;
    g.reasoning += t.reasoning ?? 0;
    g.output += t.output ?? 0;
    groups.set(effort, g);
  }
  return [...groups.values()].sort((a, b) => rankEffort(a.effort) - rankEffort(b.effort));
}

function stats(config) {
  const rows = readDecisions(config.logFile);
  if (rows.length === 0) return console.log(`no decisions yet in ${config.logFile}`);
  const layaCalls = rows.filter((r) => r.source === 'laya').length;
  const resumed = rows.reduce((sum, r) => sum + (r.continues?.length ?? 0), 0);
  console.log(`${rows.flatMap(generationsOf).length} generations, ${new Set(rows.map((r) => r.session)).size} sessions, `
    + `${layaCalls} routed by laya, ${resumed} early stops resumed`);
  const tokens = rows.map((r) => usageTokens(r.usage));
  const input = tokens.reduce((sum, t) => sum + (t.input ?? 0), 0);
  const cached = tokens.reduce((sum, t) => sum + (t.cached ?? 0), 0);
  if (input > 0) console.log(`  prompt cache: ${cached} of ${input} input tok cached (${(100 * cached / input).toFixed(1)}%)`);
  for (const g of groupByEffort(rows)) {
    console.log(`  ${g.effort.padEnd(10)} ${String(g.gens).padStart(5)} gens  ${String(Math.round(g.reasoning / g.gens)).padStart(6)} avg reasoning tok  ${g.output} output tok`);
  }
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const config = loadConfig();
  switch (cmd) {
    case 'serve': return serve(config);
    case 'install': return install(config, rest.includes('--force'), rest.includes('--global'));
    case 'uninstall': return uninstall();
    case 'setup': return setup(config, rest);
    case 'codex': return runCodex(config, rest);
    case 'tail': return tail(config);
    case 'stats': return stats(config);
    case 'status': return status(config);
    case 'stop': return stop(config);
    case 'skills': return installAgentSkills(deployDir(process.env, config.home), {
      claude: rest.includes('--claude'), force: rest.includes('--force'),
    });
    case '--version':
    case '-v': return console.log(`${NAME} v${VERSION} (build ${BUILD})`);
    default: console.log(HELP);
  }
}

main().catch((err) => {
  console.error(`${NAME}: ${err.message}`);
  process.exit(1);
});
