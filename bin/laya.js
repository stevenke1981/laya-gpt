#!/usr/bin/env node
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { loadConfig, EFFORTS } from '../src/config.js';
import { createProxy } from '../src/proxy.js';
import { formatDecision, readDecisions, usageTokens } from '../src/log.js';
import { VERSION, BUILD, APP, isOurProxy, compareBuild } from '../src/version.js';

const NAME = APP;
// Codex profile name; `codex -p layagpt` selects the provider written by `install`.
const PROFILE = 'layagpt';

const HELP = `${NAME} — one GPT model (GPT-6.1 Terra), reasoning effort low..xhigh picked by Laya, and long-task help

Usage:
  ${NAME} serve              Run the proxy in the foreground (shows live decisions)
                                (opencode/aider/crush: base URL http://127.0.0.1:8790/v1, model laya-auto)
  ${NAME} install [--force]  Write the "${PROFILE}" Codex profile ($CODEX_HOME/${PROFILE}.config.toml)
  ${NAME} codex [args...]    Start the proxy if needed, then run: codex -p ${PROFILE} [args...]
  ${NAME} tail               Follow routing decisions as they happen
  ${NAME} stats              Summarize past decisions by effort, with reasoning tokens and resumed turns
  ${NAME} status             Show the running proxy's version and whether it is stale
  ${NAME} stop               Stop the running proxy (also one started in the background)
  ${NAME} --version          Print the version and build of the code on disk

Environment:
  LAYA_PORT (8790)  LAYA_GPT_MODEL (gpt-6.1-terra)  LAYA_LEVELS (low,medium,high,xhigh)  LAYA_DEFAULT_EFFORT (medium)
  LAYA_MODE (laya|heuristic|llm|off)  LAYA_CONTINUE (on|off)  LAYA_MAX_CONTINUES (3)  LAYA_CONTINUE_THRESHOLD (0.6)
  LAYA_NUDGE (on|off)  LAYA_JUDGE_MODEL  LAYA_UPSTREAM  LAYA_HOME (~/.laya-gpt)  LAYA_QUIET=1`;

const PROFILE_MARKER = `# Generated by \`${NAME} install\``;

function profileToml(config) {
  return `${PROFILE_MARKER}. Use with: codex -p ${PROFILE}
model_provider = "${PROFILE}"
# The configured id, so the proxy routes the effort of every generation.
model = "${config.model}"
# Where a turn starts; the proxy moves it between ${config.ladder.join(' and ')}.
model_reasoning_effort = "${config.defaultEffort}"

[model_providers.${PROFILE}]
name = "Laya GPT"
base_url = "http://${config.host}:${config.port}/v1"
wire_api = "responses"
requires_openai_auth = true
`;
}

function install(config, force) {
  const codexHome = process.env.CODEX_HOME || path.join(os.homedir(), '.codex');
  const file = path.join(codexHome, `${PROFILE}.config.toml`);
  if (fs.existsSync(file) && !force && !fs.readFileSync(file, 'utf8').startsWith(PROFILE_MARKER)) {
    throw new Error(`${file} exists and was not written by ${NAME}; rerun with --force to overwrite`);
  }
  fs.mkdirSync(codexHome, { recursive: true });
  fs.writeFileSync(file, profileToml(config));
  console.log(`wrote ${file}\nrun: ${NAME} codex   (or start "${NAME} serve" and use: codex -p ${PROFILE})`);
}

/** @returns {Promise<object|null>} the /laya/health payload of whatever answers the port, or null */
async function probe(config) {
  try {
    const res = await fetch(`http://${config.host}:${config.port}/laya/health`, { signal: AbortSignal.timeout(500) });
    return res.ok ? await res.json() : null;
  } catch {
    return null;
  }
}

function foreignDescription(health) {
  return health.app ? `app "${String(health.app).slice(0, 40)}"` : 'no app id';
}

// Another server holds the port: it is reported, never signalled or reused.
function foreignPortMessage(config, health) {
  return `port ${config.port} is answered by ${foreignDescription(health)}, not a ${NAME} proxy; set LAYA_PORT to another port`;
}

async function ensureProxy(config) {
  const running = await probe(config);
  if (running) {
    if (!isOurProxy(running)) throw new Error(foreignPortMessage(config, running));
    const check = compareBuild(running);
    if (check.status === 'stale') console.error(`${NAME}: warning: ${check.message}`);
    return;
  }
  fs.mkdirSync(config.home, { recursive: true });
  const out = fs.openSync(path.join(config.home, 'proxy.log'), 'a');
  const self = fileURLToPath(import.meta.url);
  spawn(process.execPath, [self, 'serve'], { detached: true, stdio: ['ignore', out, out], windowsHide: true }).unref();
  for (let i = 0; i < 30; i++) {
    await new Promise((r) => setTimeout(r, 100));
    if (isOurProxy(await probe(config))) return;
  }
  throw new Error(`proxy did not start; see ${path.join(config.home, 'proxy.log')}`);
}

// On Windows `codex` is a .cmd shim; running it through cmd.exe would re-parse the
// user's arguments (`&`, `%VAR%`). Launch the npm package's JS entry with node instead.
function codexCommand() {
  if (process.platform !== 'win32') return { file: 'codex', prefix: [] };
  const dirs = (process.env.PATH ?? '').split(path.delimiter).filter(Boolean);
  if (process.env.APPDATA) dirs.push(path.join(process.env.APPDATA, 'npm'));
  for (const dir of dirs) {
    const entry = path.join(dir, 'node_modules', '@openai', 'codex', 'bin', 'codex.js');
    if (fs.existsSync(path.join(dir, 'codex.cmd')) && fs.existsSync(entry)) {
      return { file: process.execPath, prefix: [entry] };
    }
  }
  throw new Error(`cannot find the npm-installed Codex (codex.cmd + @openai/codex); start "${NAME} serve" and run: codex -p ${PROFILE}`);
}

async function runCodex(config, args) {
  await ensureProxy(config);
  const { file, prefix } = codexCommand();
  const child = spawn(file, [...prefix, '-p', PROFILE, ...args], { stdio: 'inherit' });
  child.on('error', (err) => {
    console.error(`${NAME}: cannot start codex: ${err.message}`);
    process.exit(1);
  });
  child.on('exit', (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
}

async function portOwnerHint(config) {
  const running = await probe(config);
  if (!running) return ` (port ${config.port} in use by something else; set LAYA_PORT)`;
  if (isOurProxy(running)) return `; a ${NAME} proxy is already there: ${compareBuild(running).message}`;
  return `; ${foreignPortMessage(config, running)}`;
}

function serve(config) {
  const { server } = createProxy(config);
  server.on('error', async (err) => {
    const hint = err.code === 'EADDRINUSE' ? await portOwnerHint(config) : '';
    console.error(`${NAME}: ${err.message}${hint}`);
    process.exit(1);
  });
  server.listen(config.port, config.host, () => {
    console.log(`${NAME} v${VERSION} (build ${BUILD}) listening on http://${config.host}:${config.port}/v1  `
      + `mode=${config.mode} model=${config.model} default=${config.defaultEffort} ladder=${config.ladder.join('→')} `
      + `continue=${config.continueTurns ? `on (max ${config.maxContinues})` : 'off'} nudge=${config.nudge ? 'on' : 'off'}`);
  });
}

async function status(config) {
  const running = await probe(config);
  if (!running) {
    console.log(`no ${NAME} proxy on http://${config.host}:${config.port} (code on disk: v${VERSION} build ${BUILD})`);
    process.exitCode = 1;
    return;
  }
  if (!isOurProxy(running)) {
    console.log(foreignPortMessage(config, running));
    process.exitCode = 1;
    return;
  }
  const check = compareBuild(running);
  console.log(`${check.message}  mode=${running.mode}`);
  if (check.status === 'stale') process.exitCode = 1;
}

const STOP_WAIT_MS = 3000;
const STOP_POLL_MS = 100;

// Stops the laya-gpt proxy that holds the port, including one started in the
// background by `laya-gpt codex`. The PID comes from /laya/health, and only a
// payload that names this app is ever signalled.
async function stop(config) {
  const running = await probe(config);
  if (!running) {
    console.log(`no ${NAME} proxy on http://${config.host}:${config.port}`);
    return;
  }
  if (!isOurProxy(running)) {
    console.error(`${NAME}: ${foreignPortMessage(config, running)}; not stopping it`);
    process.exitCode = 1;
    return;
  }
  if (!Number.isInteger(running.pid)) {
    console.error(`${NAME}: the proxy on port ${config.port} predates "${NAME} stop" and does not report its PID; stop it with:\n`
      + `  PowerShell: Stop-Process -Id (Get-NetTCPConnection -LocalPort ${config.port} -State Listen).OwningProcess\n`
      + `  macOS/Linux: kill $(lsof -t -iTCP:${config.port} -sTCP:LISTEN)`);
    process.exitCode = 1;
    return;
  }
  try {
    process.kill(running.pid);
  } catch (err) {
    if (err.code !== 'ESRCH') throw new Error(`cannot stop pid ${running.pid}: ${err.message}`);
  }
  for (let waited = 0; waited < STOP_WAIT_MS; waited += STOP_POLL_MS) {
    // Gone, or the port now belongs to another process: our proxy has stopped.
    const now = await probe(config);
    if (!isOurProxy(now) || now.pid !== running.pid) {
      console.log(`stopped ${NAME} proxy (pid ${running.pid}, v${running.version} build ${running.build})`);
      return;
    }
    await new Promise((r) => setTimeout(r, STOP_POLL_MS));
  }
  console.error(`${NAME}: pid ${running.pid} is still answering on port ${config.port} after ${STOP_WAIT_MS} ms`);
  process.exitCode = 1;
}

function tail(config) {
  let size = fs.existsSync(config.logFile) ? fs.statSync(config.logFile).size : 0;
  console.log(`following ${config.logFile} (Ctrl+C to stop)`);
  fs.mkdirSync(path.dirname(config.logFile), { recursive: true });
  fs.watchFile(config.logFile, { interval: 300 }, (cur) => {
    if (cur.size <= size) {
      size = cur.size;
      return;
    }
    const fd = fs.openSync(config.logFile, 'r');
    const buf = Buffer.alloc(cur.size - size);
    fs.readSync(fd, buf, 0, buf.length, size);
    fs.closeSync(fd);
    size = cur.size;
    for (const line of buf.toString('utf8').split('\n').filter(Boolean)) {
      try {
        console.log(formatDecision(JSON.parse(line)));
      } catch {
        // Skip a partially written line.
      }
    }
  });
}

function rankEffort(effort) {
  const i = EFFORTS.indexOf(effort);
  return i >= 0 ? i : EFFORTS.length;
}

/** Groups decisions by effort in ladder order; rows that set only the model go under "-". */
function groupByEffort(rows) {
  const groups = new Map();
  for (const r of rows) {
    const effort = r.effort ?? '-';
    const g = groups.get(effort) ?? { effort, gens: 0, reasoning: 0, output: 0 };
    const t = usageTokens(r.usage);
    g.gens++;
    g.reasoning += t.reasoning ?? 0;
    g.output += t.output ?? 0;
    groups.set(effort, g);
  }
  return [...groups.values()].sort((a, b) => rankEffort(a.effort) - rankEffort(b.effort));
}

function stats(config) {
  const rows = readDecisions(config.logFile);
  if (rows.length === 0) return console.log(`no decisions yet in ${config.logFile}`);
  const layaCost = rows.reduce((sum, r) => sum + (r.cost ?? 0), 0);
  const layaCalls = rows.filter((r) => r.source === 'laya').length;
  const resumed = rows.reduce((sum, r) => sum + (r.continues?.length ?? 0), 0);
  console.log(`${rows.length} generations, ${new Set(rows.map((r) => r.session)).size} sessions, `
    + `${layaCalls} routed by Laya ($${layaCost.toFixed(6)}), ${resumed} early stops resumed`);
  for (const g of groupByEffort(rows)) {
    console.log(`  ${g.effort.padEnd(10)} ${String(g.gens).padStart(5)} gens  ${String(Math.round(g.reasoning / g.gens)).padStart(6)} avg reasoning tok  ${g.output} output tok`);
  }
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const config = loadConfig();
  switch (cmd) {
    case 'serve': return serve(config);
    case 'install': return install(config, rest.includes('--force'));
    case 'codex': return runCodex(config, rest);
    case 'tail': return tail(config);
    case 'stats': return stats(config);
    case 'status': return status(config);
    case 'stop': return stop(config);
    case '--version':
    case '-v': return console.log(`${NAME} v${VERSION} (build ${BUILD})`);
    default: console.log(HELP);
  }
}

main().catch((err) => {
  console.error(`${NAME}: ${err.message}`);
  process.exit(1);
});
